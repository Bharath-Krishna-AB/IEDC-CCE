// Helper function to easily find a member by their ID
export const getMemberById = (memberId) => {
  for (const role of execomData) {
    const found = role.members.find(m => m.id === memberId);
    if (found) {
      return { ...found, roleTitle: role.title, roleColor: role.color };
    }
  }
  return null;
};
